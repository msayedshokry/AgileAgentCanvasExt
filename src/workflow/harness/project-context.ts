// ─── Project context pack ────────────────────────────────────────────────────
// Agents rediscover the repo on every run (which test command? which package
// manager? where do conventions live?). This detects the project's commands
// and convention files once, writes them to an editable
// <outputFolder>/project-context.md, and the prompt builder injects that file
// into every agent run. Users can edit the file; it is only regenerated when
// they ask (or when it doesn't exist).

import * as fs from 'fs';
import * as path from 'path';

export type CommandKind = 'install' | 'build' | 'test' | 'lint' | 'typecheck';

export interface ProjectCommands {
  readonly ecosystem: string[];
  readonly commands: Partial<Record<CommandKind, string>>;
  /** Convention/instruction files agents should read first. */
  readonly conventionFiles: string[];
}

export const PROJECT_CONTEXT_FILE = 'project-context.md';
const MAX_CONTEXT_CHARS = 6000;

const CONVENTION_FILES = [
  'AGENTS.md', 'CLAUDE.md', '.github/copilot-instructions.md', 'CONTRIBUTING.md',
  '.cursorrules', 'GEMINI.md', 'docs/ARCHITECTURE.md', 'ARCHITECTURE.md',
];

function exists(root: string, rel: string): boolean {
  return fs.existsSync(path.join(root, rel));
}

function readJson(file: string): Record<string, unknown> | undefined {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8')) as Record<string, unknown>;
  } catch {
    return undefined;
  }
}

function nodeRunner(root: string): string {
  if (exists(root, 'pnpm-lock.yaml')) return 'pnpm';
  if (exists(root, 'yarn.lock')) return 'yarn';
  if (exists(root, 'bun.lockb') || exists(root, 'bun.lock')) return 'bun';
  return 'npm';
}

/** Detect the project's ecosystems, standard commands and convention files. */
export function detectProjectCommands(root: string): ProjectCommands {
  const ecosystem: string[] = [];
  const commands: Partial<Record<CommandKind, string>> = {};
  const set = (kind: CommandKind, cmd: string) => { if (!commands[kind]) commands[kind] = cmd; };

  const pkg = readJson(path.join(root, 'package.json'));
  if (pkg) {
    ecosystem.push('node');
    const runner = nodeRunner(root);
    const run = (script: string) => (runner === 'npm' ? `npm run ${script}` : `${runner} ${script}`);
    const scripts = (pkg.scripts ?? {}) as Record<string, string>;
    set('install', runner === 'npm' ? 'npm install' : `${runner} install`);
    if (scripts.test && !/no test specified/.test(scripts.test)) set('test', runner === 'npm' ? 'npm test' : `${runner} test`);
    for (const s of ['build', 'compile']) if (scripts[s]) { set('build', run(s)); break; }
    if (scripts.lint) set('lint', run('lint'));
    for (const s of ['typecheck', 'check-types', 'type-check', 'tsc']) if (scripts[s]) { set('typecheck', run(s)); break; }
  }
  if (exists(root, 'pyproject.toml') || exists(root, 'requirements.txt') || exists(root, 'setup.py')) {
    ecosystem.push('python');
    set('test', 'python -m pytest');
    if (exists(root, 'ruff.toml') || /\[tool\.ruff\]/.test(safeRead(path.join(root, 'pyproject.toml')))) set('lint', 'ruff check .');
  }
  if (exists(root, 'Cargo.toml')) {
    ecosystem.push('rust');
    set('build', 'cargo build');
    set('test', 'cargo test');
    set('lint', 'cargo clippy');
  }
  if (exists(root, 'go.mod')) {
    ecosystem.push('go');
    set('build', 'go build ./...');
    set('test', 'go test ./...');
    set('lint', 'go vet ./...');
  }
  if (exists(root, 'pom.xml')) {
    ecosystem.push('java');
    set('test', 'mvn -q test');
  } else if (exists(root, 'build.gradle') || exists(root, 'build.gradle.kts')) {
    ecosystem.push('java');
    set('test', exists(root, 'gradlew') ? './gradlew test' : 'gradle test');
  }
  if (exists(root, 'Makefile') && /^test:/m.test(safeRead(path.join(root, 'Makefile')))) set('test', 'make test');

  return { ecosystem, commands, conventionFiles: CONVENTION_FILES.filter((f) => exists(root, f)) };
}

function safeRead(file: string): string {
  try {
    return fs.readFileSync(file, 'utf-8');
  } catch {
    return '';
  }
}

export function renderProjectContext(detected: ProjectCommands): string {
  const lines = [
    '# Project context for agents',
    '',
    '<!-- Generated by Agile Agent Canvas. Edit freely: agents read this file before every run.',
    '     Regenerate with "Agile Agent Canvas: Refresh Project Context". -->',
    '',
    `Ecosystem: ${detected.ecosystem.join(', ') || 'unknown'}`,
    '',
    '## Commands',
    '',
  ];
  const order: CommandKind[] = ['install', 'build', 'typecheck', 'lint', 'test'];
  const known = order.filter((k) => detected.commands[k]);
  if (known.length === 0) lines.push('_None detected. Add the commands agents should use._');
  for (const k of known) lines.push(`- **${k}:** \`${detected.commands[k]}\``);
  lines.push('', '## Read first', '');
  if (detected.conventionFiles.length === 0) lines.push('_No convention files found._');
  for (const f of detected.conventionFiles) lines.push(`- \`${f}\``);
  lines.push('', '## Notes', '', '_Add architecture notes, do/don\'t rules and gotchas here._', '');
  return lines.join('\n');
}

export function contextFilePath(outputFolder: string): string {
  return path.join(outputFolder, PROJECT_CONTEXT_FILE);
}

/** Write the context file if missing (or when `force`). Returns its path. */
export function ensureProjectContext(root: string, outputFolder: string, force = false): string {
  const file = contextFilePath(outputFolder);
  if (force || !fs.existsSync(file)) {
    fs.mkdirSync(outputFolder, { recursive: true });
    fs.writeFileSync(file, renderProjectContext(detectProjectCommands(root)), 'utf-8');
  }
  return file;
}

/** Context text for prompts (bounded); empty when there is no file. */
export function readProjectContext(outputFolder: string): string {
  const text = safeRead(contextFilePath(outputFolder)).trim();
  return text.length > MAX_CONTEXT_CHARS ? text.slice(0, MAX_CONTEXT_CHARS) + '\n…(truncated)' : text;
}

/** The test/verify command from the context file (users may have edited it). */
export function verifyCommandFromContext(outputFolder: string): string | undefined {
  const text = safeRead(contextFilePath(outputFolder));
  const test = text.match(/^- \*\*test:\*\* `([^`]+)`/m);
  return test?.[1]?.trim() || undefined;
}
